#!/bin/bash

# This file is documentation for how to get started with DeepSeek v4.

# This file runs Step 2 on v5p-128 / tpu7x-128 on a daily basis.
# 1. Convert the HuggingFace checkpoint (bf16) to MaxText-compatible checkpoint (bf16):
#    Scanned format is better for training; unscanned format is better for decoding.
# 2. Run logit checks (unscanned and scanned), pre-training, SFT, and decoding.

set -ex
set -o pipefail

# Ensure JetStream and dependencies are installed for inference.decode
if ! python3 -m pip show jetstream &>/dev/null; then
    python3 -m src.dependencies.scripts.install_pre_train_extra_deps --with-tf
fi

export MODEL_NAME='deepseek4-1600b'
export TOKENIZER_PATH="${TOKENIZER_PATH:-deepseek-ai/DeepSeek-V4-Pro}"

# Installing torch for checkpoint conversion and forward_pass_logit_checker.py
python3 -m pip install torch --index-url https://download.pytorch.org/whl/cpu

if [ -z "${BASE_OUTPUT_PATH}" ]; then
  # Non-Googlers please remember to point `BASE_OUTPUT_PATH` to GCS buckets that you own, this script uses internal buckets for testing.
  # this bucket will store all the files generated by MaxText during a run
  export BASE_OUTPUT_PATH="gs://runner-maxtext-logs/$(date +%Y-%m-%d-%H-%M)"
  echo "BASE_OUTPUT_PATH is not set"
fi
BASE_OUTPUT_PATH="${BASE_OUTPUT_PATH%/}"
echo "using BASE_OUTPUT_PATH = ${BASE_OUTPUT_PATH}"

# Dated public conversion verified by the end-to-end run. Override these
# to test a fresh conversion from 1_test_deepseek.sh, which writes
# ${BASE_OUTPUT_PATH}/{scanned,unscanned}/0/items.
SCANNED_CKPT_PATH="${SCANNED_CKPT_PATH:-gs://maxtext-deepseek/deepseek4-1600b/2026-10-03/scanned/0/items}"
UNSCANNED_CKPT_PATH="${UNSCANNED_CKPT_PATH:-gs://maxtext-deepseek/deepseek4-1600b/2026-10-03/unscanned/0/items}"

INDEXER_TOPK="${INDEXER_TOPK:-1024}"

# Test whether the forward pass logits match the golden logits.
# To prevent container image-bundled golden assets from shadowing the canonical
# golden logits, fetch directly from GOLDEN_LOGITS_PATH and log the effective path.
if [ "${RUN_LOGIT:-true}" = "true" ] || [ "${RUN_SCANNED_LOGIT_CHECK:-true}" = "true" ]; then
  GOLDEN_LOGITS_PATH="${GOLDEN_LOGITS_PATH:-gs://maxtext-test-assets/golden_data_deepseek4-1600b.jsonl}"
  if [[ "${GOLDEN_LOGITS_PATH}" =~ ^gs:// ]]; then
    GOLDEN_LOGITS_DISK_LOCATION="/tmp/golden_data_${MODEL_NAME}.jsonl"
    echo "Fetching golden logits from ${GOLDEN_LOGITS_PATH}..."
    gcloud storage cp "${GOLDEN_LOGITS_PATH}" "${GOLDEN_LOGITS_DISK_LOCATION}"
  else
    GOLDEN_LOGITS_DISK_LOCATION="${GOLDEN_LOGITS_PATH}"
  fi
  echo "Effective --golden_logits_path=${GOLDEN_LOGITS_DISK_LOCATION}"

  if [ "${RUN_LOGIT:-true}" = "true" ]; then
    echo "=== STAGE: unscanned logit check ==="
    # shellcheck disable=SC2086
    python3 -m tests.utils.forward_pass_logit_checker \
      "${MAXTEXT_CONFIGS_DIR:-${MAXTEXT_REPO_ROOT:-$PWD}/src/maxtext/configs}/base.yml" \
      base_output_directory="${BASE_OUTPUT_PATH}" \
      run_name=ds4-parity \
      load_parameters_path="${UNSCANNED_CKPT_PATH}" \
      scan_layers=False \
      attention=dot_product \
      per_device_batch_size="${LOGIT_PER_DEVICE_BATCH_SIZE:-1}" \
      model_name="${MODEL_NAME}" \
      override_model_config=True \
      indexer_topk="${INDEXER_TOPK}" \
      max_target_length=512 \
      max_prefill_predict_length=512 \
      activations_in_float32="${LOGIT_ACTIVATIONS_IN_FLOAT32:-false}" \
      matmul_precision="${LOGIT_MATMUL_PRECISION:-highest}" \
      float32_logits="${LOGIT_FLOAT32_LOGITS:-false}" \
      float32_qk_product="${LOGIT_FLOAT32_QK_PRODUCT:-false}" \
      sparse_matmul="${LOGIT_SPARSE_MATMUL:-True}" \
      megablox="${LOGIT_MEGABLOX:-False}" \
      ici_fsdp_parallelism=-1 \
      dcn_fsdp_parallelism="${DCN_FSDP_PARALLELISM:--1}" \
      dcn_data_parallelism="${DCN_DP:-1}" \
      ici_expert_parallelism="${ICI_EXPERT_PARALLELISM:-16}" \
      ici_tensor_parallelism="${LOGIT_ICI_TP:-1}" \
      ici_context_parallelism="${LOGIT_ICI_CP:-1}" \
      weight_dtype=bfloat16 \
      dtype=bfloat16 \
      ${LOGIT_EXTRA_FLAGS:-} \
      --golden_logits_path="${GOLDEN_LOGITS_DISK_LOCATION}" \
      --max_kl_div="${MAX_KL_DIV:-0.42}" \
      --clip_logits_epsilon=1e-6
  fi

  if [ "${RUN_SCANNED_LOGIT_CHECK:-true}" = "true" ]; then
    echo "=== STAGE: scanned logit check ==="
    # shellcheck disable=SC2086
    python3 -m tests.utils.forward_pass_logit_checker \
      "${MAXTEXT_CONFIGS_DIR:-${MAXTEXT_REPO_ROOT:-$PWD}/src/maxtext/configs}/base.yml" \
      base_output_directory="${BASE_OUTPUT_PATH}" \
      run_name=ds4-parity-scanned \
      load_parameters_path="${SCANNED_CKPT_PATH}" \
      scan_layers=True \
      attention=dot_product \
      per_device_batch_size="${LOGIT_PER_DEVICE_BATCH_SIZE:-1}" \
      model_name="${MODEL_NAME}" \
      override_model_config=True \
      indexer_topk="${INDEXER_TOPK}" \
      max_target_length=512 \
      max_prefill_predict_length=512 \
      activations_in_float32="${LOGIT_ACTIVATIONS_IN_FLOAT32:-false}" \
      matmul_precision="${LOGIT_MATMUL_PRECISION:-highest}" \
      float32_logits="${LOGIT_FLOAT32_LOGITS:-false}" \
      float32_qk_product="${LOGIT_FLOAT32_QK_PRODUCT:-false}" \
      sparse_matmul="${LOGIT_SPARSE_MATMUL:-True}" \
      megablox="${LOGIT_MEGABLOX:-False}" \
      ici_fsdp_parallelism=-1 \
      dcn_fsdp_parallelism="${DCN_FSDP_PARALLELISM:--1}" \
      dcn_data_parallelism="${DCN_DP:-1}" \
      ici_expert_parallelism="${ICI_EXPERT_PARALLELISM:-16}" \
      ici_tensor_parallelism="${LOGIT_ICI_TP:-1}" \
      ici_context_parallelism="${LOGIT_ICI_CP:-1}" \
      weight_dtype=bfloat16 \
      dtype=bfloat16 \
      ${LOGIT_EXTRA_FLAGS:-} \
      --golden_logits_path="${GOLDEN_LOGITS_DISK_LOCATION}" \
      --max_kl_div="${MAX_KL_DIV:-0.42}" \
      --clip_logits_epsilon=1e-6
  fi
fi

if [ "${RUN_PRETRAIN:-true}" = "true" ]; then
  echo "=== STAGE: pre-train ==="
  # An empty load_parameters_path parses to None and fails schema validation,
  # so drop the flag rather than passing a blank value.
  PRETRAIN_LOAD_PARAMS="${PRETRAIN_LOAD_PARAMS-${SCANNED_CKPT_PATH}}"
  PRETRAIN_LOAD_FLAG=""
  if [ -n "${PRETRAIN_LOAD_PARAMS}" ]; then
    PRETRAIN_LOAD_FLAG="load_parameters_path=${PRETRAIN_LOAD_PARAMS}"
  fi
  # PRETRAIN_DCN_EP > 1 (expert parallelism over DCN) is unverified: DCN EP 4 hit a TPU core halt in
  # the first step on v5p-128 x4.
  # shellcheck disable=SC2086
  python3 -m maxtext.trainers.pre_train.train \
    "${MAXTEXT_CONFIGS_DIR:-${MAXTEXT_REPO_ROOT:-$PWD}/src/maxtext/configs}/base.yml" \
    base_output_directory="${BASE_OUTPUT_PATH}" \
    run_name=pre_training \
    model_name="${MODEL_NAME}" \
    tokenizer_type=huggingface \
    tokenizer_path="${TOKENIZER_PATH}" \
    dataset_type=synthetic \
    enable_checkpointing="${PRETRAIN_ENABLE_CKPT:-True}" \
    attention="${PRETRAIN_ATTENTION:-dot_product}" \
    use_tokamax_splash="${PRETRAIN_USE_TOKAMAX_SPLASH:-False}" \
    sparse_matmul="${PRETRAIN_SPARSE_MATMUL:-True}" \
    use_tokamax_gmm="${PRETRAIN_USE_TOKAMAX_GMM:-False}" \
    dtype=bfloat16 \
    weight_dtype=bfloat16 \
    per_device_batch_size=1 \
    steps="${STEPS:-20}" \
    max_target_length="${MAX_TARGET_LENGTH:-1024}" \
    override_model_config=True \
    ici_fsdp_parallelism=-1 \
    dcn_fsdp_parallelism="${DCN_FSDP_PARALLELISM:--1}" \
    ici_expert_parallelism="${ICI_EXPERT_PARALLELISM:-16}" \
    dcn_data_parallelism="${PRETRAIN_DCN_DP:-1}" \
    dcn_expert_parallelism="${PRETRAIN_DCN_EP:-1}" \
    opt_type=sgd \
    save_checkpoint_on_start=false \
    save_checkpoint_on_completion=false \
    indexer_sparse_training="${PRETRAIN_INDEXER_SPARSE_TRAINING:-True}" \
    indexer_loss_scaling_factor="${PRETRAIN_INDEXER_LOSS_SCALING:-1.0}" \
    indexer_topk="${PRETRAIN_INDEXER_TOPK:-64}" \
    ${PRETRAIN_LOAD_FLAG} \
    ${PRETRAIN_EXTRA_FLAGS:-} 2>&1 | tee /tmp/pretrain_output.log

  total_loss=$(awk -F"loss: " '/completed step:/ {print $2}' /tmp/pretrain_output.log | awk -F"," '{print $1}' | tail -n 1 | tr -d ' ' | tr '[:upper:]' '[:lower:]')
  if [ -z "$total_loss" ] || [ "$total_loss" = "nan" ] || [ "$total_loss" = "inf" ] || [ "$(awk -v v="$total_loss" 'BEGIN { print (v + 0 > 0) ? 1 : 0 }')" != "1" ]; then
    echo "ERROR: Total training loss is not strictly positive: ${total_loss}"
    exit 1
  fi

  if [ "$(echo "${PRETRAIN_INDEXER_SPARSE_TRAINING:-True}" | tr '[:upper:]' '[:lower:]')" = "true" ]; then
    lm_loss=$(awk -F"lm_loss: " '/completed step:/ {print $2}' /tmp/pretrain_output.log | awk -F"," '{print $1}' | tail -n 1 | tr -d ' ' | tr '[:upper:]' '[:lower:]')
    if [ -z "$lm_loss" ] || [ "$lm_loss" = "nan" ] || [ "$lm_loss" = "inf" ]; then
      echo "ERROR: Invalid or missing lm_loss: ${lm_loss}"
      exit 1
    fi
    is_positive=$(awk -v v="$lm_loss" 'BEGIN { print (v + 0 > 0) ? 1 : 0 }')
    if [ "$is_positive" != "1" ]; then
      echo "ERROR: lm_loss is not strictly positive: ${lm_loss}"
      exit 1
    fi
  fi
fi

if [ "${RUN_SFT:-true}" = "true" ]; then
  echo "=== STAGE: sft ==="
  SFT_CONFIG="${MAXTEXT_CONFIGS_DIR:-${MAXTEXT_REPO_ROOT:-$PWD}/src/maxtext/configs}/post_train/sft.yml"
  # Pinned GCS copy of HuggingFaceH4/ultrachat_200k (train_sft split).
  SFT_DATA_FLAGS=(
    hf_path=parquet
    "hf_train_files=${SFT_HF_TRAIN_FILES:-gs://maxtext-dataset/hf/ultrachat_200k/train_sft-*.parquet}"
    train_split=train
  )

  # Fail fast if the SFT input pipeline masks completion EOS tokens out of the loss.
  JAX_PLATFORMS=cpu python3 "${MAXTEXT_REPO_ROOT:-$PWD}/tests/end_to_end/tpu/deepseek/sft_eos_probe.py" \
    "${SFT_CONFIG}" \
    base_output_directory="${BASE_OUTPUT_PATH}" \
    run_name=sft_eos_probe \
    model_name="${MODEL_NAME}" \
    tokenizer_type=huggingface \
    tokenizer_path="${TOKENIZER_PATH}" \
    max_target_length=1024 \
    "${SFT_DATA_FLAGS[@]}"

  # load_parameters_path restores the converted weights. Checkpointing stays enabled (the base.yml
  # default); these flags only turn off saving, which would dominate a 5-step run on 1.6T params.
  # shellcheck disable=SC2086
  python3 -m maxtext.trainers.post_train.sft.train_sft_native \
    "${SFT_CONFIG}" \
    base_output_directory="${BASE_OUTPUT_PATH}" \
    run_name=sft \
    model_name="${MODEL_NAME}" \
    tokenizer_type=huggingface \
    tokenizer_path="${TOKENIZER_PATH}" \
    "${SFT_DATA_FLAGS[@]}" \
    load_parameters_path="${SCANNED_CKPT_PATH}" \
    scan_layers=True \
    attention=dot_product \
    sparse_matmul=True \
    use_tokamax_gmm=False \
    dtype=bfloat16 \
    weight_dtype=bfloat16 \
    per_device_batch_size=1 \
    steps="${SFT_STEPS:-5}" \
    max_target_length=1024 \
    override_model_config=True \
    ici_fsdp_parallelism=-1 \
    dcn_fsdp_parallelism="${DCN_FSDP_PARALLELISM:--1}" \
    ici_expert_parallelism="${ICI_EXPERT_PARALLELISM:-16}" \
    dcn_data_parallelism=1 \
    opt_type=sgd \
    learning_rate=1e-6 \
    save_checkpoint_on_start=false \
    save_checkpoint_on_completion=false \
    checkpoint_period=100000 \
    async_checkpointing=false \
    ${SFT_EXTRA_FLAGS:-} 2>&1 | tee /tmp/sft_output.log

  # Every logged step must have a finite, strictly positive loss.
  if ! awk -F"loss: " '
    BEGIN { found = 0; failed = 0 }
    /completed step:.*loss:/ {
      split($2, a, ",");
      loss = a[1];
      gsub(/[ \t\r\n]/, "", loss);
      loss_lower = tolower(loss);
      if (loss_lower == "nan" || loss_lower == "inf" || loss_lower == "-inf" || !(loss + 0 > 0)) {
        print "ERROR: SFT loss is not finite and strictly positive: " loss;
        failed = 1;
        exit 1;
      }
      found = 1;
    }
    END {
      if (failed) {
        exit 1;
      }
      if (!found) {
        print "ERROR: No SFT step losses found";
        exit 1;
      }
    }
  ' /tmp/sft_output.log; then
    exit 1
  fi
fi

if [ "${RUN_DECODE:-true}" = "true" ]; then
  # The official V4-Pro model greedily emits a leading " O" (token 541) for this BOS-first prompt; V4-Flash does not.
  echo "=== STAGE: decode ==="
  # shellcheck disable=SC2086
  python3 -m maxtext.inference.decode \
    "${MAXTEXT_CONFIGS_DIR:-${MAXTEXT_REPO_ROOT:-$PWD}/src/maxtext/configs}/base.yml" \
    base_output_directory="${BASE_OUTPUT_PATH}" \
    run_name=decode \
    model_name="${MODEL_NAME}" \
    tokenizer_type=huggingface \
    tokenizer_path="${TOKENIZER_PATH}" \
    hf_access_token="${HF_TOKEN:-}" \
    load_parameters_path="${UNSCANNED_CKPT_PATH}" \
    scan_layers=False \
    attention=dot_product \
    sparse_matmul="${DECODE_SPARSE_MATMUL:-True}" \
    use_tokamax_gmm="${DECODE_USE_TOKAMAX_GMM:-False}" \
    dtype=bfloat16 \
    weight_dtype=bfloat16 \
    per_device_batch_size=1 \
    max_prefill_predict_length="${DECODE_MAX_PREFILL:-64}" \
    max_target_length="${DECODE_MAX_TARGET:-512}" \
    override_model_config=True \
    ici_fsdp_parallelism=-1 \
    dcn_fsdp_parallelism="${DCN_FSDP_PARALLELISM:--1}" \
    dcn_data_parallelism="${DCN_DP:-1}" \
    ici_tensor_parallelism="${DECODE_ICI_TP:-1}" \
    ici_expert_parallelism="${ICI_EXPERT_PARALLELISM:-16}" \
    checkpoint_storage_concurrent_gb=1024 \
    mla_naive_kvcache=false \
    prompt="An attention function can be described as..." \
    autoregressive_decode_assert="${DECODE_ASSERT:-O mapping a query and a set of key-value pairs to an output}" \
    ${DECODE_EXTRA_FLAGS:-}
fi

echo "DeepSeek V4 end-to-end tests completed successfully!"
