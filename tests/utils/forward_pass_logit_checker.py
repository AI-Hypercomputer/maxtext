# This script, forward_pass_logit_checker.py, verifies the correctness of logits generated by the MaxText or HuggingFace
# implementation of a model by comparing them against a reference "golden" logits file for a set of input prompts.
#
# It supports multiple models and expects a reference file in JSON Lines (.jsonl) or pickle (.pickle or .pkl) format,
# specified via the --golden_logits_path argument. If not provided, it defaults to:
#   tests/assets/golden_logits/golden_data_<model_name>.jsonl
# For example:
#   tests/assets/golden_logits/golden_data_llama2-7b.jsonl
#
# Each line in the golden .jsonl file should be a dictionary with the following keys:
#   1. prompt: a string prompt, e.g., "I love to"
#   2. tokens: the token IDs resulting from tokenizing the prompt
#   3. logits: the expected (golden) logits output by the model for the given prompt
#
# The script runs a forward pass using the MaxText implementation and compares the resulting logits against the golden
# ones, asserting that they match within a tolerance.
#
# Utilities and Colab notebooks used to generate the golden logits are available in tests/assets/logits_generation.
# For example:
#   tests/assets/logits_generation/golden_llama2-7b_export.ipynb
#
# NOTE: Be careful of updates. This file affects scripts under `tests/end_to_end/tpu` for nightly tests.

"""Check if the logits generated by a model's src/maxtext/HF implementation matches golden logits for the same inputs.

Usage:

1. Comparing MaxText against a pre-generated HF golden logits file
(supported for both text-only and multimodal models; recommended for large models and repeated tests):
For multimodal models, you must pre-generate the HuggingFace golden logits file first using generate_hf_golden_logits.py:

python3 -m tests.assets.logits_generation.generate_hf_golden_logits \
    --model-id=Qwen/Qwen3-VL-2B-Instruct --hf-model-path=path/to/qwen3-vl-2b \
    --prompts="Describe this image" --image-paths=tests/assets/test_image.jpg \
    --output-path=golden_qwen3-vl-2b_vision.jsonl \
    --apply-chat-template --output-format=json

Then run the following command to check if the MaxText checkpoint matches the golden logits:

python3 -m tests.utils.forward_pass_logit_checker src/maxtext/configs/base.yml \
    tokenizer_path=path/to/qwen3-vl-2b \
    load_parameters_path=<your-bucket>/qwen3-vl-2b/maxtext_ckpt/0/items model_name=qwen3-vl-2b \
    use_multimodal=true scan_layers=false dtype=float32 per_device_batch_size=1 \
    prompt="Describe this image" image_path=tests/assets/test_image.jpg \
    --max_kl_div=0.1 --golden_logits_path=golden_qwen3-vl-2b_vision.jsonl

Note: Pre-generating golden logits is also supported and recommended for large text-only models and repeated tests.

2. Running the HuggingFace model on-the-fly to compare against MaxText (supported for text-only models):

python3 -m tests.utils.forward_pass_logit_checker src/maxtext/configs/base.yml \
    tokenizer_path=path/to/qwen3-0.6b \
    load_parameters_path=<your-bucket>/qwen3-0.6b/maxtext_ckpt/0/items model_name=qwen3-0.6b \
    use_multimodal=false per_device_batch_size=1 dtype=float32 \
    --max_kl_div=0.1 --run_hf_model=true --hf_model_path=path/to/qwen3-0.6b
"""

