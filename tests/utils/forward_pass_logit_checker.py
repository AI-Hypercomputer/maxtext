def _local_checkpoint_dir(path):
  """Returns a local directory with the checkpoint at `path`, copying a gs:// checkpoint to a temp dir first."""
  if not path.startswith("gs://"):
    return path
  import atexit  # pylint: disable=import-outside-toplevel
  import shutil  # pylint: disable=import-outside-toplevel
  import subprocess  # pylint: disable=import-outside-toplevel
  import tempfile  # pylint: disable=import-outside-toplevel

  local = tempfile.mkdtemp(prefix="hf_reference_")
  atexit.register(shutil.rmtree, local, ignore_errors=True)
  max_logging.warning(
      f"Copying the whole checkpoint {path} to {local} for the reference model: make sure the local disk can hold it"
      " (hundreds of GB for a full-size model), or pass a local --hf_model_path."
  )
  subprocess.run(["gcloud", "storage", "cp", "-r", path.rstrip("/") + "/*", local], check=True)
  return local


def detect_reference_model(hf_model_path: str) -> str:
  """Picks a reference implementation from the checkpoint's config.json `model_type` (local or gs://)."""
  if not hf_model_path:
    return ""
  from etils import epath  # pylint: disable=import-outside-toplevel

  config_path = epath.Path(hf_model_path) / "config.json"
  if not config_path.exists():
    return ""
  model_type = json.loads(config_path.read_text()).get("model_type", "")
  return model_type if model_type in _REFERENCE_MODELS else ""


_detect_reference_model = detect_reference_model


class _ReferenceModelOutput:
  """Container wrapping reference-model output logits."""

  def __init__(self, logits):
    self.logits = logits


class _ReferenceModel:
  """Adapts a reference model to the `hf_model(**inputs).logits` interface."""

  def __init__(self, model):
    self.model = model

  def __call__(self, input_ids, **unused_kwargs):
    return _ReferenceModelOutput(self.model(input_ids, full_logits=True).float())


def load_reference_model(reference_model, hf_model_path, torch_dtype, config, tokenizer):
  """Loads a plain-PyTorch reference (see `_REFERENCE_MODELS`) wrapped to look like a transformers model."""
  import importlib  # pylint: disable=import-outside-toplevel

  if reference_model not in _REFERENCE_MODELS:
    raise ValueError(f"Unknown reference model {reference_model}; choose from {sorted(_REFERENCE_MODELS)}")
  if torch is None:
    raise ImportError("PyTorch is required to load a plain-PyTorch reference model.")
  repo_root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
  if repo_root not in sys.path:
    sys.path.insert(0, repo_root)
  runner = importlib.import_module(_REFERENCE_MODELS[reference_model])
  dtype = "fp32" if torch_dtype == torch.float32 else "bf16"
  max_logging.log(f"Loading the {reference_model} reference model ({dtype}) from {hf_model_path}")
  model, _ = runner.load_reference_model(
      _local_checkpoint_dir(hf_model_path), dtype=dtype, max_seq_len=config.max_target_length, tokenizer=tokenizer
  )
  return _ReferenceModel(model)


_load_reference_model = load_reference_model


def get_data(golden_data_point, config):
  """Extracts model inputs, golden logits, and sequence length from a golden data record."""
  model_prefix = config.model_name.split("-")[0]

  max_logging.log(f"config.global_batch_size_to_train_on={config.global_batch_size_to_train_on}")
  audio_values = None
  if getattr(config, "use_audio", False) and golden_data_point.get("audio_values") is not None:
    audio_values = np.asarray(golden_data_point["audio_values"], dtype=np.float32)
    audio_values = np.concatenate([audio_values] * config.global_batch_size_to_train_on, axis=0)
    max_logging.log(f"audio_values.shape={audio_values.shape}")

  if config.use_multimodal and audio_values is None:
    assert "pixel_values" in golden_data_point, "no image found in golden data while use_multimodal=True"
  if config.use_multimodal and "pixel_values" in golden_data_point:
    pixel_values = np.asarray(golden_data_point["pixel_values"], dtype=np.float32)
    max_logging.log(f"pixel_values.shape = {pixel_values.shape}")
    # Gemma3 and Gemma4 models expect (num_images, height, width, channels).
    if model_prefix in ["gemma3", "gemma4"]:
      if pixel_values.ndim == 2:
        h, w = config.image_size_for_vit
        p = config.patch_size_for_vit
        c = pixel_values.shape[-1] // (p * p)
        pixel_values = np.reshape(pixel_values, (h // p, w // p, p, p, c))
        pixel_values = np.transpose(pixel_values, (0, 2, 1, 3, 4))
        pixel_values = np.reshape(pixel_values, (h, w, c))
      else:
        pixel_values = np.transpose(pixel_values, (1, 2, 0))
    elif model_prefix in ["llama4"]:
      pixel_values = pixel_values[None, :]
    elif model_prefix in ["qwen3"]:
      grid_thw = np.asarray(golden_data_point["image_grid_thw"])
      if grid_thw.ndim == 2:
        grid_t, grid_h, grid_w = grid_thw[0]
      else:
        grid_t, grid_h, grid_w = grid_thw
      tps = config.temporal_patch_size_for_vit
      p = config.patch_size_for_vit
      c = config.num_channels_for_vit
      pixel_values = np.reshape(pixel_values, (c, int(grid_t * tps), int(grid_h * p), int(grid_w * p)))
    pixel_values = np.stack([pixel_values for _ in range(config.global_batch_size_to_train_on)])
  else:
    pixel_values = None

  original_ids = np.asarray(golden_data_point["tokens"], dtype=np.int32)
  seq_len = len(original_ids)

  if seq_len > config.max_target_length:
    raise ValueError(
        f"Golden data sequence length ({seq_len}) is greater than max_target_length ({config.max_target_length})"
    )

  s = (config.global_batch_size_to_train_on, config.max_target_length)

  padded_ids = np.pad(original_ids, (0, config.max_target_length - seq_len), "constant", constant_values=0)
  ids = np.stack([padded_ids for _ in range(config.global_batch_size_to_train_on)])

  logits = np.asarray(golden_data_point["logits"], dtype=np.float32)
  if "formatted_prompt" in golden_data_point:
    prompt = golden_data_point["formatted_prompt"]
  else:
    prompt = golden_data_point["prompt"]
  max_logging.log(f' prompt="{prompt}" raw ids (first 20)={original_ids[:20]}, logits.shape = {logits.shape}')

  decoder_segment_ids = np.zeros(s, dtype=np.int32)
  decoder_segment_ids[:, :seq_len] = DECODING_ACTIVE_SEQUENCE_INDICATOR

  if model_prefix in ["qwen3"] and config.use_mrope:
    from maxtext.multimodal import processor_qwen3_omni  # pylint: disable=import-outside-toplevel

    image_grid_thw = np.atleast_2d(golden_data_point["image_grid_thw"]) if "image_grid_thw" in golden_data_point else None
    video_grid_thw = np.atleast_2d(golden_data_point["video_grid_thw"]) if "video_grid_thw" in golden_data_point else None

    attention_mask = np.zeros(s, dtype=np.int32)
    attention_mask[:, :seq_len] = 1

    position_ids, _ = processor_qwen3_omni.get_rope_index(
        input_ids=ids,
        image_grid_thw=image_grid_thw,
        video_grid_thw=video_grid_thw,
        attention_mask=attention_mask,
        spatial_merge_size=config.spatial_merge_size_for_vit,
        position_id_per_seconds=config.position_id_per_seconds,
        config=config,
    )
    decoder_positions = position_ids.astype(np.int32)
  else:
    decoder_positions = np.stack(
        [np.arange(config.max_target_length, dtype=np.int32) for _ in range(config.global_batch_size_to_train_on)]
    )
  return ids, decoder_segment_ids, decoder_positions, logits, seq_len, pixel_values, audio_values


def make_eval_step_nnx(
    model: Any,
    mesh: jax.sharding.Mesh,
    logical_axis_rules: Sequence[tuple[str, Any]] | None = None,
):
  """Builds a cached @jax.jit eval step for an NNX model inside mesh and axis_rules."""
  nnx_graphdef, nnx_state = nnx.split(model)
  rules_tuple = tuple(logical_axis_rules) if logical_axis_rules is not None else ()

  @jax.jit
  def eval_step(  # pylint: disable=too-many-positional-arguments,too-many-arguments
      step_state,
      ids,
      decoder_positions,
      decoder_segment_ids,
      images=None,
      image_masks=None,
      audios=None,
  ):
    # Mesh and logical axis rules must be active at trace time so PartitionSpecs resolve properly.
    with mesh, nn_partitioning.axis_rules(rules_tuple):
      nnx_model = nnx.merge(nnx_graphdef, step_state)
      return nnx_model(
          decoder_input_tokens=ids,
          decoder_positions=decoder_positions,
          decoder_segment_ids=decoder_segment_ids,
          encoder_images=images,
          encoder_image_masks=image_masks,
          encoder_audios=audios,
          enable_dropout=False,
      )

  return eval_step, nnx_state


def init_maxtext_model(config, mesh: jax.sharding.Mesh, *, preloaded_model: Any = None):
  """Returns `preloaded_model` if provided, otherwise loads the MaxText model and optional LoRA adapter."""
  if preloaded_model is not None:
    return preloaded_model
  max_logging.log("Initializing MaxText model")
  model = model_creation_utils.from_pretrained(config, mesh=mesh, model_mode=MODEL_MODE_TRAIN)
  if getattr(config, "lora", None) is not None and config.lora.enable_lora:
    model = lora_utils.apply_lora_to_model(model, mesh, config)
    if config.lora.lora_restore_path:
      lora_utils.restore_lora_from_path(model, config)
  return model


_init_maxtext_model = init_maxtext_model


def load_tokenizer(config, *, hf_model_path: str = "", trust_remote_code: bool = True, run_hf_model: bool = False):
  """Loads the HuggingFace tokenizer when configured paths are available."""
  hf_token = config.hf_access_token
  tokenizer_load_paths = []
  if hf_model_path:
    tokenizer_load_paths.append(hf_model_path)
  if config.tokenizer_path:
    tokenizer_load_paths.append(config.tokenizer_path)

  hf_model_id = HF_IDS.get(config.model_name)
  if hf_model_id:
    tokenizer_load_paths.append(hf_model_id)

  tokenizer = None
  last_exception = None
  for path in tokenizer_load_paths:
    try:
      max_logging.log(f"Loading tokenizer from {path}.")
      tokenizer = AutoTokenizer.from_pretrained(path, token=hf_token, trust_remote_code=trust_remote_code)
      break
    except Exception as e:  # pylint: disable=broad-except,broad-exception-caught
      last_exception = e
      max_logging.log(f"Failed to load tokenizer from {path}: {e}")

  if tokenizer is None and last_exception is not None and run_hf_model:
    raise last_exception

  if tokenizer is not None and config.model_name.startswith(("llama3.1", "mixtral")):
    tokenizer.pad_token = tokenizer.eos_token
  return tokenizer


def main(config, test_args, *, preloaded_model: Any = None):  # pylint: disable=redefined-outer-name
  """Verifies MaxText forward logits against pre-loaded golden files or a live HF/PyTorch reference."""
  devices_array = maxtext_utils.create_device_mesh(config)
  mesh = jax.sharding.Mesh(devices_array, config.mesh_axes)
  tokenizer = load_tokenizer(
      config,
      hf_model_path=getattr(test_args, "hf_model_path", ""),
      trust_remote_code=getattr(test_args, "trust_remote_code", True),
      run_hf_model=getattr(test_args, "run_hf_model", False),
  )

  if not test_args.run_hf_model:
    model = init_maxtext_model(config, mesh, preloaded_model=preloaded_model)
    eval_step_nnx, nnx_state = make_eval_step_nnx(model, mesh, getattr(config, "logical_axis_rules", None))

    if test_args.golden_logits_path == "":
      input_golden_data_path = os.path.join(
          MAXTEXT_TEST_ASSETS_ROOT,
          "golden_logits",
          f"golden_data_{config.model_name}.jsonl",
      )
    else:
      input_golden_data_path = test_args.golden_logits_path
    input_golden_data_path = Path(input_golden_data_path)
    if input_golden_data_path.suffix == ".jsonl":
      max_logging.log("loading hf goldens from jsonl file")
      import jsonlines  # pylint: disable=import-outside-toplevel

      with jsonlines.open(input_golden_data_path, "r") as f:
        golden_data = list(f)
    elif input_golden_data_path.suffix in (".pickle", ".pkl"):
      max_logging.log("loading hf goldens from pickle file")
      import pickle  # pylint: disable=import-outside-toplevel

      with open(input_golden_data_path, "rb") as f:
        golden_data = pickle.load(f)
    else:
      raise ValueError("golden_logits_path must end with .jsonl, .pickle, or .pkl")

    max_logging.log(f"loaded {len(golden_data)} golden data points")
    all_data_to_save = []
    max_kl_seen = 0.0
    for golden_data_index, golden_data_point in enumerate(golden_data):
      max_logging.log(f"\n--- Comparing forward pass for golden data index: {golden_data_index} ---")
      ids, decoder_segment_ids, decoder_positions, golden_logits, seq_len, images, audios = get_data(
          golden_data_point, config
      )
      max_logging.log("maxtext forward pass")
      full_train_logits = eval_step_nnx(nnx_state, ids, decoder_positions, decoder_segment_ids, images, None, audios)

      # Only batch element 0 is compared; slice before the allgather so the full [batch, seq, vocab]
      # logits are never materialized per host.
      full_train_logits = full_train_logits[:1]
      full_train_logits = jax.experimental.multihost_utils.process_allgather(full_train_logits, tiled=True)
      if full_train_logits.ndim == 4:
        full_train_logits = jnp.reshape(full_train_logits, (-1, config.max_target_length, config.vocab_size))
      full_train_logits = full_train_logits[:, :seq_len, :]

      token_size = int(test_args.token_size) if test_args.token_size else seq_len
      if full_train_logits.shape[-1] != golden_logits.shape[-1]:
        max_logging.log(
            f"Vocab size mismatch: train logits vocab size {full_train_logits.shape[-1]}, "
            f"golden logits vocab size {golden_logits.shape[-1]}. "
            "Comparing up to the smaller vocab size."
        )
      min_vocab_size = min(full_train_logits.shape[-1], golden_logits.shape[-1])

      start_index = 1 if test_args.skip_first_token else 0
      train_logits_slice = full_train_logits[0, start_index:token_size, :min_vocab_size]
      golden_logits_slice = golden_logits[start_index:token_size, :min_vocab_size]

      if train_logits_slice.shape[0] > 2:
        max_logging.log(f"\n[logits: token {start_index + 2}]")
        max_logging.log(f"{golden_logits_slice[2]=}")
        max_logging.log(f"{train_logits_slice[2]=}")

      abs_diff = jnp.abs(train_logits_slice - golden_logits_slice)
      safe_golden_logits = jnp.where(golden_logits_slice == 0, 1e-8, golden_logits_slice)
      rel_diff = abs_diff / jnp.abs(safe_golden_logits)

      max_abs_diff_idx = jnp.unravel_index(jnp.argmax(abs_diff), abs_diff.shape)
      max_rel_diff_idx = jnp.unravel_index(jnp.argmax(rel_diff), rel_diff.shape)

      max_abs_diff_val = abs_diff[max_abs_diff_idx]
      max_rel_diff_val = rel_diff[max_rel_diff_idx]
      msg = (
          "\n[numerical difference]\n"
          f"Max absolute difference: {max_abs_diff_val:.2e} at index {max_abs_diff_idx}\n"
          f"  (Train: {train_logits_slice[max_abs_diff_idx]:.2e}, Golden: {golden_logits_slice[max_abs_diff_idx]:.2e})\n"
          f"Max relative difference: {max_rel_diff_val:.2e} at index {max_rel_diff_idx}\n"
          f"  (Train: {train_logits_slice[max_rel_diff_idx]:.2e}, Golden: {golden_logits_slice[max_rel_diff_idx]:.2e})"
      )
      max_logging.log(msg)

      if convert_jax_weight_to_torch is not None and torch is not None:
        mt_last_token_logits = (
            convert_jax_weight_to_torch(train_logits_slice[-1:, :])
            if isinstance(train_logits_slice, jax.Array)
            else torch.tensor(train_logits_slice[-1:, :])
        )
        hf_last_token_logits = (
            convert_jax_weight_to_torch(golden_logits_slice[-1:, :])
            if isinstance(golden_logits_slice, jax.Array)
            else torch.tensor(golden_logits_slice[-1:, :])
        )
      else:
        mt_last_token_logits = np.asarray(train_logits_slice[-1:, :])
        hf_last_token_logits = np.asarray(golden_logits_slice[-1:, :])

      tokens_maxtext = get_top_k_tokens_scores(mt_last_token_logits, tokenizer, k=10, description="MaxText model")
      tokens_hf = get_top_k_tokens_scores(hf_last_token_logits, tokenizer, k=10, description="HF model")
      compare_top_tokens(converted_tokens=tokens_maxtext, golden_tokens=tokens_hf)

      kl_div = _per_token_kl_2d(
          golden_logits_slice,
          train_logits_slice,
          clip_logits_epsilon=test_args.clip_logits_epsilon,
      )

      ignore_token_ids = []
      if getattr(config, "use_multimodal", False) and "qwen3" in config.model_name.lower():
        from maxtext.multimodal.processor_qwen3_omni import QwenTokens  # pylint: disable=import-outside-toplevel

        qwen_tokens = QwenTokens(config)
        ignore_token_ids = [
            qwen_tokens.vision_start,
            qwen_tokens.vision_end,
            qwen_tokens.image_pad,
            qwen_tokens.video_pad,
        ]

      if ignore_token_ids:
        slice_ids = ids[0, start_index:token_size]
        mask = np.ones_like(slice_ids, dtype=bool)
        for ignore_id in ignore_token_ids:
          mask = mask & (slice_ids != ignore_id)
        kl_div = np.where(mask, kl_div, 0.0)

      max_kl_div_val = float(np.max(kl_div))
      max_kl_div_idx = int(np.argmax(kl_div))
      max_kl_seen = max(max_kl_seen, max_kl_div_val)

      per_token_kl = "" if config.use_multimodal else f"KL divergence = {kl_div}, "
      max_logging.log(
          f"\n[KL divergence]\n"
          f"{per_token_kl} max KL divergence = {max_kl_div_val} at index {max_kl_div_idx}, "
          f"the corresponding token id is {ids[0, max_kl_div_idx + start_index]}"
      )

      if jax.process_index() == 0 and test_args.output_logits_path:
        data_to_save = {
            "prompt": golden_data_point["prompt"],
            "tokens": ids[0, :seq_len].tolist(),
            "logits": full_train_logits[0].tolist(),
        }
        all_data_to_save.append(data_to_save)

      if test_args.atol is not None:
        max_logging.log("\n[test criteria]")
        max_logging.log(
            f"Checking Numerical Differences between train logits and golden logits against "
            f"atol={test_args.atol} rtol={test_args.rtol}."
        )
        rtol_val = float(test_args.rtol)
        atol_val = float(test_args.atol)
        assert jax.numpy.allclose(
            train_logits_slice, golden_logits_slice, rtol=rtol_val, atol=atol_val, equal_nan=False
        ), (
            f"forward logit samples failed gates: Logits do not match closely enough. "
            f"Required rtol={test_args.rtol}, atol={test_args.atol}."
        )

      if test_args.max_kl_div is not None:
        max_logging.log(
            f"Checking KL Divergence between train distribution and golden distribution against "
            f"threshold {test_args.max_kl_div}."
        )
        assert bool(np.all(kl_div < test_args.max_kl_div)), (
            f"forward logit samples failed gates: KL divergence values {max_kl_div_val} "
            f"exceed the threshold {test_args.max_kl_div}"
        )

    if jax.process_index() == 0 and test_args.output_logits_path:
      import jsonlines  # pylint: disable=import-outside-toplevel

      os.makedirs(os.path.dirname(test_args.output_logits_path), exist_ok=True)
      with jsonlines.open(test_args.output_logits_path, "a") as f:
        f.write(all_data_to_save)
      max_logging.log(f"Saved logits to {test_args.output_logits_path}")

      if test_args.gcs_output_logits_path:
        bucket_name = test_args.gcs_output_logits_path.split("/")[2]
        destination_blob_name = "/".join(
            test_args.gcs_output_logits_path.split("/")[3:] + test_args.output_logits_path.split("/")[-1:]
        )
        upload_blob(bucket_name, test_args.output_logits_path, destination_blob_name)
        max_logging.log(f"Uploaded logits to {test_args.gcs_output_logits_path}")

    return {"passed": True, "max_kl": max_kl_seen}

  if test_args.hf_model_path == "":
    raise ValueError("run_hf_model requires hf_model_path")
  if test_args.max_kl_div is None:
    raise ValueError("--run_hf_model=true requires --max_kl_div to be specified.")
  if torch is None or F is None or convert_jax_weight_to_torch is None:
    raise ImportError("PyTorch is required when --run_hf_model=true.")

  hf_token = config.hf_access_token
  dtype_mapping = {
      "bfloat16": torch.bfloat16,
      "float32": torch.float32,
      "float16": torch.float16,
      jnp.bfloat16: torch.bfloat16,
      jnp.float32: torch.float32,
      jnp.float16: torch.float16,
  }
  dtype_key = jnp.dtype(config.dtype).name.lower()
  torch_dtype = dtype_mapping.get(dtype_key, torch.bfloat16)
  max_logging.log(f"Loading HF model with dtype: {torch_dtype} (derived from config.dtype: {config.dtype})")

  reference_model = (
      test_args.reference_model if test_args.reference_model else _detect_reference_model(test_args.hf_model_path)
  )
  if reference_model:
    hf_model = _load_reference_model(reference_model, test_args.hf_model_path, torch_dtype, config, tokenizer)
  else:
    if "qwen3-vl" in config.model_name.lower():
      from transformers import Qwen3VLForConditionalGeneration  # pylint: disable=import-outside-toplevel

      model_class = Qwen3VLForConditionalGeneration
    else:
      model_class = AutoModelForCausalLM

    hf_model = model_class.from_pretrained(
        test_args.hf_model_path,
        torch_dtype=torch_dtype,
        token=hf_token,
        trust_remote_code=test_args.trust_remote_code,
    )
  hf_lora_path = getattr(config, "hf_lora_adapter_path", "")
  if hf_lora_path:
    max_logging.log(f"Loading HF PEFT LoRA adapter from {hf_lora_path}")
    try:
      from peft import PeftModel  # pylint: disable=import-outside-toplevel
    except ImportError as exc:
      raise ImportError("peft library is required to load HF LoRA adapter. Run `pip install peft`.") from exc
    hf_model = PeftModel.from_pretrained(hf_model, hf_lora_path)

  model = _init_maxtext_model(config, mesh, preloaded_model=preloaded_model)
  eval_step_nnx, nnx_state = make_eval_step_nnx(model, mesh, getattr(config, "logical_axis_rules", None))

  prompts = ["I love to", "Today is a", "What is the", build_long_prompt()]
  all_data_to_save = []
  for input_text in prompts:
    max_logging.log(f"\n--- Prompt: {input_text[:80]}{'...' if len(input_text) > 80 else ''} ---")

    inputs = tokenizer(
        input_text, return_tensors="pt", padding=True, max_length=config.max_target_length, truncation=True
    )
    actual_seq_len = inputs["input_ids"].shape[1]

    mt_ids = jnp.asarray(inputs["input_ids"], dtype=jnp.int32)
    if mt_ids.shape[0] != config.global_batch_size_to_train_on:
      mt_ids = jnp.repeat(mt_ids, config.global_batch_size_to_train_on // mt_ids.shape[0], axis=0)

    s = (config.global_batch_size_to_train_on, config.max_target_length)
    mt_decoder_segment_ids_full = jnp.zeros(s, dtype=jnp.int32) + DECODING_ACTIVE_SEQUENCE_INDICATOR
    mt_decoder_segment_ids = mt_decoder_segment_ids_full[:, :actual_seq_len]

    mt_decoder_positions_full = jnp.stack(
        [jnp.arange(config.max_target_length, dtype=jnp.int32) for _ in range(config.global_batch_size_to_train_on)]
    )
    mt_decoder_positions = mt_decoder_positions_full[:, :actual_seq_len]

    with torch.no_grad():
      hf_logits_torch = hf_model(**inputs).logits

    mt_logits_jax = eval_step_nnx(nnx_state, mt_ids, mt_decoder_positions, mt_decoder_segment_ids)
    mt_logits_jax_sliced = mt_logits_jax[:, :actual_seq_len, :]
    mt_logits_torch = convert_jax_weight_to_torch(mt_logits_jax_sliced)

    hf_last_token_logits = hf_logits_torch[:, -1, :]
    mt_last_token_logits = mt_logits_torch[:, -1, :]

    tokens_maxtext = get_top_k_tokens_scores(mt_last_token_logits, tokenizer, k=10, description="MaxText model")
    tokens_hf = get_top_k_tokens_scores(hf_last_token_logits, tokenizer, k=10, description="HF model")
    compare_top_tokens(converted_tokens=tokens_maxtext, golden_tokens=tokens_hf)

    start_index = 1 if test_args.skip_first_token else 0
    check_kl_divergence(
        mt_logits_torch[0, start_index:].unsqueeze(0),
        hf_logits_torch[0, start_index:].unsqueeze(0),
        atol=test_args.max_kl_div,
        clip_logits_epsilon=test_args.clip_logits_epsilon,
    )
    if jax.process_index() == 0 and test_args.output_logits_path:
      data_to_save = {
          "mt_logits": mt_logits_torch[0].tolist(),
          "hf_logits": hf_logits_torch[0].tolist(),
      }
      all_data_to_save.append(data_to_save)

  if jax.process_index() == 0 and test_args.output_logits_path:
    import jsonlines  # pylint: disable=import-outside-toplevel

    os.makedirs(os.path.dirname(test_args.output_logits_path), exist_ok=True)
    with jsonlines.open(test_args.output_logits_path, "a") as f:
      f.write(all_data_to_save)
    max_logging.log(f"Saved logits to {test_args.output_logits_path}")

    if test_args.gcs_output_logits_path:
      bucket_name = test_args.gcs_output_logits_path.split("/")[2]
      destination_blob_name = "/".join(
          test_args.gcs_output_logits_path.split("/")[3:] + test_args.output_logits_path.split("/")[-1:]
      )
      upload_blob(bucket_name, test_args.output_logits_path, destination_blob_name)
      max_logging.log(f"Uploaded logits to {test_args.gcs_output_logits_path}")

  return None


def run_checker(config, test_args, *, preloaded_model: Any = None):  # pylint: disable=redefined-outer-name
  """CLI execution wrapper that translates deterministic gate and code errors to exit code 42."""
  try:
    main(config, test_args, preloaded_model=preloaded_model)
  except (DeterministicGateError, AssertionError) as e:
    err_str = str(e)
    if (
        isinstance(e, DeterministicGateError)
        or "forward logit samples failed gates" in err_str
        or "KL divergence values" in err_str
    ):
      max_logging.log(f"Deterministic gate failure: {e}; exiting with code 42")
      sys.exit(EXIT_DETERMINISTIC_GATE_FAIL)
    raise
  except DETERMINISTIC_CODE_ERRORS as exc:
    det_err_msg = f"[DETERMINISTIC_CODE_ERROR] Unhandled {type(exc).__name__}: {exc}"
    max_logging.log(det_err_msg)
    print(det_err_msg, file=sys.stderr)
    traceback.print_exc()
    sys.stdout.flush()
    sys.stderr.flush()
    sys.exit(EXIT_DETERMINISTIC_GATE_FAIL)


def build_arg_parser() -> argparse.ArgumentParser:
  """Builds the CLI `ArgumentParser` for `forward_pass_logit_checker`."""
  arg_parser = argparse.ArgumentParser()
  arg_parser.add_argument("--atol", type=float, required=False, default=None)
  arg_parser.add_argument("--rtol", type=float, required=False, default=1e-05)
  arg_parser.add_argument("--token_size", type=int, required=False)
  arg_parser.add_argument("--max_kl_div", type=float, required=False, default=None)
  arg_parser.add_argument("--golden_logits_path", type=str, required=False, default="")
  arg_parser.add_argument("--hf_model_path", type=str, required=False, default="")
  arg_parser.add_argument("--run_hf_model", type=str2bool, required=False, default=False)
  arg_parser.add_argument("--output_logits_path", type=str, required=False, default="")
  arg_parser.add_argument("--gcs_output_logits_path", type=str, required=False, default="")
  arg_parser.add_argument("--clip_logits_epsilon", type=float, required=False, default=None)
  arg_parser.add_argument(
      "--skip_first_token",
      action="store_true",
      required=False,
      default=False,
      help="Skip the first token during comparison to ignore BOS/init mismatches.",
  )
  arg_parser.add_argument(
      "--ckpt_type",
      type=str,
      required=False,
      default="linen",
      choices=["linen", "nnx"],
      help="Checkpoint format to load: 'linen' (default) or 'nnx'.",
  )
  arg_parser.add_argument(
      "--trust_remote_code", type=str2bool, required=False, default=True, help="from_pretrained: trust_remote_code"
  )
  arg_parser.add_argument(
      "--reference_model",
      type=str,
      required=False,
      default="",
      choices=["", *_REFERENCE_MODELS],
      help="With --run_hf_model, compare against this plain-PyTorch reference implementation instead of a"
      " transformers model (auto-detected from a local checkpoint's config.json model_type).",
  )
  return arg_parser


