def get_top_k_tokens_scores(logits_tensor, tokenizer_instance, k=10, description=""):
  """Get the top-k tokens and their scores from a given logits tensor."""
  max_logging.log(f"\n--- {description} top {k} tokens ---")
  collected_tokens = []
  tokens = []
  if torch is not None and hasattr(logits_tensor, "dim"):
    topk_results = torch.topk(logits_tensor[0], k=k)
    for i in range(k):
      tok_id = topk_results.indices[i].item()
      score = topk_results.values[i].item()
      tok = tokenizer_instance.decode(tok_id) if tokenizer_instance is not None else str(tok_id)
      entry = {"id": int(tok_id), "token": tok.strip(), "score": float(score)}
      collected_tokens.append(entry)
      tokens.append(entry)
  else:
    arr = np.asarray(logits_tensor)[0]
    top_indices = np.argsort(arr)[::-1][:k]
    for idx in top_indices:
      tok_id = int(idx)
      score = float(arr[tok_id])
      tok = tokenizer_instance.decode(tok_id) if tokenizer_instance is not None else str(tok_id)
      entry = {"id": tok_id, "token": tok.strip(), "score": score}
      collected_tokens.append(entry)
      tokens.append(entry)
  # Prepare data for logging
  table_str = f"| {'Token ID':<10} | {'Token':<20} | {'Score':<10} |\n"
  table_str += f"|{'-'*12}|{'-'*22}|{'-'*12}|\n"
  for d in collected_tokens:
    table_str += f"| {d['id']:<10} | {d['token']:<20} | {d['score']:<10.4f} |\n"
  max_logging.log(table_str)
  return tokens


def compare_top_tokens(converted_tokens, golden_tokens):
  """
  Compares two lists of top tokens and calculates similarity metrics.

  Args:
      converted_tokens: top tokens from the converted model.
      golden_tokens:  top tokens from the golden model.
  """
  # Extract the sets of token IDs for comparison
  converted_ids = {token["id"] for token in converted_tokens}
  golden_ids = {token["id"] for token in golden_tokens}

  # --- Metric 1: Overlap Count & Jaccard Similarity ---
  intersection = converted_ids.intersection(golden_ids)
  union = converted_ids.union(golden_ids)

  overlap_count = len(intersection)
  jaccard_similarity = overlap_count / len(union) if union else 0.0

  # --- Metric 2: Rank Agreement ---
  rank_matches = 0
  min_len = min(len(converted_tokens), len(golden_tokens))
  for i in range(min_len):
    if converted_tokens[i]["id"] == golden_tokens[i]["id"]:
      rank_matches += 1

  rank_agreement = (rank_matches / min_len) * 100 if min_len > 0 else 0.0

  metrics = {
      "overlap_count": f"{overlap_count}/{min_len}",
      "jaccard_similarity": jaccard_similarity,
      "rank_agreement_percentage": rank_agreement,
  }

  max_logging.log("\n--- Similarity Metrics of Top Tokens ---")
  table_str = f"| {'Metric':<30} | {'Value':<20} |\n"
  table_str += f"|{'-'*32}|{'-'*22}|\n"
  for key, value in metrics.items():
    table_str += f"| {key:<30} | {str(value):<20} |\n"
  max_logging.log(table_str)


def check_kl_divergence(model_logits, golden_logits, atol=0.02, clip_logits_epsilon=None):
  """
  Calculates KL divergence D_KL(P_golden || Q_model) over a batch of sequences.

  Args:
      model_logits: Logits from the converted model (Batch, SeqLen, VocabSize).
      golden_logits: Logits from the golden model (Batch, SeqLen, VocabSize).
      token_size: The number of vocabulary entries to consider for the comparison.
                  (Effectively vocab_size_to_compare).
  """
  # 1. Select the relevant vocabulary slice from the logits.
  token_size = min(model_logits.shape[2], golden_logits.shape[2])
  model_logits_sliced = model_logits[..., :token_size]
  golden_logits_sliced = golden_logits[..., :token_size]

  # 2. Reshape
  b, s, v = model_logits_sliced.shape
  model_logits_reshaped = model_logits_sliced.reshape(b * s, v)
  golden_logits_reshaped = golden_logits_sliced.reshape(b * s, v)

  # 3. Get the probability distributions.
  golden_probabilities = F.softmax(golden_logits_reshaped, dim=-1)

  # Apply clipping and re-normalization to predicted probabilities ONLY
  if clip_logits_epsilon is not None:
    model_probabilities = F.softmax(model_logits_reshaped, dim=-1)
    model_probabilities = torch.clamp(model_probabilities, min=clip_logits_epsilon)
    model_probabilities = model_probabilities / model_probabilities.sum(dim=-1, keepdim=True)
    # Compute manual log-probabilities of the model. Safe because of clamping.
    model_log_probabilities = torch.log(model_probabilities)
  else:
    model_log_probabilities = F.log_softmax(model_logits_reshaped, dim=-1)

  # 4. Calculate avg KL divergence for all token distributions.
  # use 'batchmean'; the sum of the KL divergences for each token in the batch
  # and then divides by the number of tokens (b * s)
  kl_div_value = F.kl_div(
      input=model_log_probabilities,
      target=golden_probabilities,
      reduction="batchmean",  # Use 'batchmean' for the average KL per token.
      log_target=False,
  )

  max_logging.log(f"\nAverage KL divergence per token (D_KL(P_golden || Q_model)): {kl_div_value.item():.2e}")

  # To find the max KL divergence for any single token in the set
  # use reduction='none'.
  kl_divs_per_token = F.kl_div(
      input=model_log_probabilities, target=golden_probabilities, reduction="none", log_target=False
  ).sum(
      dim=-1
  )  # Sum over the vocab dim to get a single KL value per token

  # Log per-token KL divergences
  formatted_list = [f"{x:.2e}" for x in kl_divs_per_token.tolist()]
  max_logging.log(f"Per-token KL Divergences: \n{formatted_list}")

  max_kl_div = kl_divs_per_token.max()
  max_logging.log(f"\nMax KL divergence for a single token in the set: {max_kl_div.item():.2e}")

  assert max_kl_div < atol, f"KL divergence values {max_kl_div.item():.2e} exceed the threshold {atol}"


# Reference implementations for models without a transformers implementation: model type -> loader module.
_REFERENCE_MODELS = {
    "deepseek_v41": "tests.utils.deepseek_v41_reference.runner",
}


def _local_checkpoint_dir(path):
  """Returns a local directory with the checkpoint at `path`, copying a gs:// checkpoint to a temp dir first."""
  if not path.startswith("gs://"):
    return path
  import subprocess  # pylint: disable=import-outside-toplevel
  import tempfile  # pylint: disable=import-outside-toplevel

  local = tempfile.mkdtemp(prefix="hf_reference_")
  max_logging.log(f"Copying {path} to {local} for the reference model.")
  subprocess.run(["gcloud", "storage", "cp", "-r", path.rstrip("/") + "/*", local], check=True)
  return local


def _detect_reference_model(hf_model_path):
  """Picks a reference implementation from the checkpoint's config.json `model_type`, if it needs one."""
  if not hf_model_path or hf_model_path.startswith("gs://"):
    return ""
  config_path = os.path.join(hf_model_path, "config.json")
  if not os.path.exists(config_path):
    return ""

  with open(config_path, encoding="utf-8") as f:
    model_type = json.load(f).get("model_type", "")
  return model_type if model_type in _REFERENCE_MODELS else ""


class _ReferenceModelOutput:

  def __init__(self, logits):
    self.logits = logits


class _ReferenceModel:
  """Adapts a reference model to the `hf_model(**inputs).logits` interface used below."""

  def __init__(self, model):
    self.model = model

  def __call__(self, input_ids, **unused_kwargs):
    return _ReferenceModelOutput(self.model(input_ids, full_logits=True).float())


def _load_reference_model(reference_model, hf_model_path, torch_dtype, config, tokenizer):
  """Loads a registered PyTorch reference model wrapped for logit comparison."""
  import importlib  # pylint: disable=import-outside-toplevel

  if reference_model not in _REFERENCE_MODELS:
    raise ValueError(f"Unknown reference model {reference_model}; choose from {sorted(_REFERENCE_MODELS)}")
  runner = importlib.import_module(_REFERENCE_MODELS[reference_model])
  dtype = "fp32" if torch_dtype == torch.float32 else "bf16"
  max_logging.log(f"Loading the {reference_model} reference model ({dtype}) from {hf_model_path}")
  model, _ = runner.load_reference_model(
      _local_checkpoint_dir(hf_model_path), dtype=dtype, max_seq_len=config.max_target_length, tokenizer=tokenizer
  )
  return _ReferenceModel(model)


def _resolve_sample_name(golden_data_point: Mapping[str, Any], fallback_label: str) -> str:
  """Resolves sample name from `name` or `sample_id` (falling back to `fallback_label`)."""
  if "name" in golden_data_point and golden_data_point["name"] is not None:
    name_val = golden_data_point["name"]
    name_str = str(np.asarray(name_val).item()) if isinstance(name_val, np.ndarray) else str(name_val)
    if name_str:
      return name_str
  if "sample_id" in golden_data_point and golden_data_point["sample_id"] is not None:
    sid_val = golden_data_point["sample_id"]
    sid_str = str(np.asarray(sid_val).item()) if isinstance(sid_val, np.ndarray) else str(sid_val)
    if sid_str:
      return sid_str
  return fallback_label


