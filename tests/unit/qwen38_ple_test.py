def test_qsa_cached_steps_match_full_reference_beyond_budget():

  cfg = config()
  cfg.num_attention_heads = 4
  cfg.num_key_value_heads = 2
  cfg.head_dim = 8
  cfg.indexer_n_heads = 2
  cfg.indexer_kv_heads = 1
  cfg.indexer_head_dim = 8
  cfg.indexer_budget = 8
  cfg.indexer_compress_ratio = 4
  cfg.rope_parameters = {
      "rope_type": "default",
      "rope_theta": 10000000.0,
      "partial_rotary_factor": 1.0,
      "mrope_section": [2, 1, 1],
      "mrope_interleaved": True,
  }
  cfg._attn_implementation = "eager"
  ref = Qwen4ExpTextAttention(cfg, 3)
  w = weights(ref)
  x = np.random.default_rng(24).normal(size=(2, 13, 16)).astype(np.float32)
  positions = torch.arange(13)[None, None, :].expand(3, 2, -1)
  cos, sin = Qwen4ExpTextRotaryEmbedding(cfg)(torch.from_numpy(x), positions)
  causal = torch.arange(13)[None, :] <= torch.arange(13)[:, None]
  mask = torch.where(causal, 0.0, torch.finfo(torch.float32).min)[None, None, :, :].expand(2, 1, -1, -1)
  expected = ref(torch.from_numpy(x), (cos, sin), mask)[0].detach().numpy()
  state = {
      "key": jnp.zeros((2, 16, 2, 8)),
      "value": jnp.zeros((2, 16, 2, 8)),
      "index_key": jnp.zeros((2, 16, 8)),
      "valid": jnp.zeros((2, 16), jnp.bool_),
  }
  pieces = []
  for start, end in [(0, 5), (5, 6), (6, 9), (9, 10), (10, 13)]:
    inputs = jnp.asarray(x[:, start:end])
    step_positions = jnp.broadcast_to(jnp.arange(start, end), (2, end - start))
    active = jnp.ones((2, end - start), jnp.bool_)
    if start == 0:
      inputs = jnp.pad(inputs, ((0, 0), (0, 3), (0, 0)))
      step_positions = jnp.pad(step_positions, ((0, 0), (0, 3)))
      active = jnp.pad(active, ((0, 0), (0, 3)))
    result, state = attention_forward(
        inputs,
        w,
        cfg,
        positions=step_positions,
        mask=active,
        state=state,
        return_state=True,
    )
    assert np.asarray(state["valid"][:, 0]).all()
    pieces.append(result[:, : end - start])
  np.testing.assert_allclose(jnp.concatenate(pieces, axis=1), expected, atol=2e-6, rtol=2e-4)


