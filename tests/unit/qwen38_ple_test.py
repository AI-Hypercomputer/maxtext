def test_cache_leaves_roundtrip_through_nnx_pure_dict():

  values = {
      "attention": {"conv": jnp.zeros((1, 3, 8)), "recurrent": jnp.zeros((1, 2, 8, 8))},
      "count": jnp.zeros((1,), jnp.int32),
  }
  module = nnx.Module()
  with jax.set_mesh(Mesh(np.asarray(jax.devices()), ("data",))), logical_axis_rules([("cache_batch", "data")]):
    module.cache = cache_tree(values, "cache_batch")
  state = nnx.state(module, nnx.Cache)
  pure = state.to_pure_dict()
  nnx.replace_by_pure_dict(state, pure)
  nnx.update(module, state)
  update_cache(module.cache, {**values, "count": jnp.array([4])})
  assert cache_values(module.cache)["count"].item() == 4
  for _, leaf in nnx.to_flat_state(state):
    assert leaf.get_metadata()["out_sharding"][0] == "cache_batch"


def test_lookup_validation_does_not_dispatch_backend_reductions():
  class HostArray:

    def __array__(self, dtype=None, copy=None):
      return np.array([True, True], dtype=dtype)

    def all(self):
      raise AssertionError("A JAX-like reduction inside a callback would deadlock")

  validate_lookup_rows(HostArray())
  with pytest.raises(ValueError, match="missing"):
    validate_lookup_rows(np.array([True, False]))


@pytest.mark.parametrize("algorithm", ["greedy", "weighted", "nucleus", "topk", "composite"])
def test_greedy_sampler_keeps_engine_token_dtype_with_x64(algorithm):
  logits = jnp.array([[1.0, 3.0, 2.0]], dtype=jnp.float32)
  result = sampling(logits, jax.random.key(0), algorithm, topk=2, nucleus_topp=0.8)
  assert result.dtype == jnp.int32
  assert result.shape == (1,)
  assert 0 <= result.item() < 3
  if algorithm == "greedy":
    np.testing.assert_array_equal(result, [1])
