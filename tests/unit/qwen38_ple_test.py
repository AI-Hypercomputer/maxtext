def config():
  return Qwen4ExpTextConfig(
      hidden_size=16,
      hc_count=4,
      hc_lowrank=8,
      ple_embed_dim=32,
      ngram_vocab_size_base=17,
      heads_per_ngram=2,
      ngram_size=3,
      ple_conv_kernel_size=4,
      vocab_size=64,
      eos_token_id=63,
      num_hidden_layers=4,
      layer_types=["linear_attention"] * 3 + ["full_attention"],
  )


def weights(module):
  gen = torch.Generator().manual_seed(12)
  with torch.no_grad():
    for parameter in module.parameters():
      parameter.copy_(torch.randn(parameter.shape, generator=gen) * 0.1)
  return {k: jnp.asarray(v.detach().numpy()) for k, v in module.state_dict().items()}


def test_gated_residual_matches_official_reference():

  cfg = config()
  ref = Qwen4ExpTextGatedResidual(cfg)
  w = weights(ref)
  x = np.random.default_rng(3).normal(size=(2, 7, 64)).astype(np.float32)
  expected = ref(torch.from_numpy(x))
  actual = gated_residual(jnp.asarray(x), w, cfg.hidden_size, cfg.hc_count, cfg.rms_norm_eps)
  for a, b in zip(actual, expected):
    np.testing.assert_allclose(a, b.detach().numpy(), atol=2e-6, rtol=2e-5)


def test_ple_hash_and_dilated_convolution_match_reference():

  cfg = config()
  ref = Qwen4ExpTextPLELayer(cfg, layer_idx=1, ple_layer_index=0)
  w = weights(ref)
  ids = np.array([[2, 3, 63, 7, 8, 9, 10], [63, 2, 2, 63, 63, 4, 5]])
  x = np.random.default_rng(8).normal(size=(2, 7, 64)).astype(np.float32)
  actual_ids = ngram_ids(
      jnp.asarray(ids),
      w["ple_embedding.layer_multipliers"],
      w["ple_embedding.ngram_heads_vocab_sizes"],
      w["ple_embedding.ngram_heads_offsets"],
      63,
      3,
      2,
  )
  seen = []
  ref.ple_embedding.ngram_embedding.register_forward_pre_hook(lambda m, args: seen.append(args[0]))
  expected = ref(torch.from_numpy(x), torch.from_numpy(ids), None)
  np.testing.assert_array_equal(actual_ids, seen[0].numpy())
  actual = ple_forward(
      jnp.asarray(x),
      w["ple_embedding.ngram_embedding.weight"][actual_ids].reshape(2, 7, 32),
      w,
      cfg.hidden_size,
      cfg.hc_count,
      cfg.ngram_size,
      cfg.rms_norm_eps,
  )
  np.testing.assert_allclose(actual, expected.detach().numpy(), atol=2e-6, rtol=2e-5)


