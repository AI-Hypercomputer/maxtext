@pytest.mark.parametrize("layer_idx,length", [(0, 7), (1, 7), (3, 7), (3, 12)])
def test_decoder_matches_official_reference(layer_idx, length):

  cfg = config()
  cfg.num_attention_heads = 4
  cfg.num_key_value_heads = 2
  cfg.head_dim = 8
  cfg.indexer_n_heads = 2
  cfg.indexer_kv_heads = 1
  cfg.indexer_head_dim = 8
  cfg.indexer_budget = 8
  cfg.indexer_compress_ratio = 4
  cfg.linear_num_key_heads = 2
  cfg.linear_num_value_heads = 4
  cfg.linear_key_head_dim = 8
  cfg.linear_value_head_dim = 8
  cfg.num_experts = 4
  cfg.num_experts_per_tok = 2
  cfg.moe_intermediate_size = 8
  cfg.shared_expert_intermediate_size = 8
  cfg.ple_layer_ids = [2]
  cfg.rope_parameters = {
      "rope_type": "default",
      "rope_theta": 10000000.0,
      "partial_rotary_factor": 1.0,
      "mrope_section": [2, 1, 1],
      "mrope_interleaved": True,
  }
  cfg._attn_implementation = "eager"
  ref = Qwen4ExpTextDecoderLayer(cfg, layer_idx)
  w = weights(ref)
  ids = torch.tensor([[2, 3, 63, 7, 8, 9, 10], [63, 2, 2, 63, 63, 4, 5]])
  ids = torch.nn.functional.pad(ids, (0, length - 7), value=4)
  x = np.random.default_rng(8).normal(size=(2, length, 64)).astype(np.float32)
  positions = torch.arange(length)[None, None, :].expand(3, 2, -1)
  rotary = Qwen4ExpTextRotaryEmbedding(cfg)
  cos, sin = rotary(torch.from_numpy(x), positions)
  mask = torch.where(torch.arange(length)[None, :] <= torch.arange(length)[:, None], 0.0, torch.finfo(torch.float32).min)[
      None, None, :, :
  ].expand(2, 1, -1, -1)
  expected = ref(torch.from_numpy(x), (cos, sin), mask, ple_input_ids=ids)
  actual = decoder_forward(jnp.asarray(x), jnp.asarray(ids.numpy()), w, cfg, layer_idx)
  np.testing.assert_allclose(actual, expected.detach().numpy(), atol=3e-5, rtol=3e-4)


def test_gdn_cached_steps_equal_full_reference():

  cfg = config()
  cfg.linear_num_key_heads = 2
  cfg.linear_num_value_heads = 4
  cfg.linear_key_head_dim = 8
  cfg.linear_value_head_dim = 8
  cfg.output_gate_type = "sigmoid"
  ref = Qwen4ExpTextGatedDeltaNet(cfg, 0)
  w = weights(ref)
  x = np.random.default_rng(19).normal(size=(2, 9, 16)).astype(np.float32)
  expected = ref(torch.from_numpy(x)).detach().numpy()
  state = None
  pieces = []
  for start, end in [(0, 4), (4, 5), (5, 7), (7, 8), (8, 9)]:
    out, state = gdn_forward(jnp.asarray(x[:, start:end]), w, cfg, state=state, return_state=True)
    pieces.append(out)
  np.testing.assert_allclose(jnp.concatenate(pieces, axis=1), expected, atol=2e-6, rtol=2e-4)


